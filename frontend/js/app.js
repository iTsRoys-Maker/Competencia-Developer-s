function initNavbar() {
  const token = localStorage.getItem('token');
  const user = localStorage.getItem('user');
  let parsedUser = null;
  try { parsedUser = user ? JSON.parse(user) : null; } catch (e) {}
  const isLoggedIn = !!token;
  const isAdmin = parsedUser?.rol === 'ADMIN';
  const currentPage = window.location.pathname.split('/').pop() || 'index.html';

  const nav = document.createElement('header');
  nav.className = 'navbar';
  nav.innerHTML = `
    <a href="index.html" class="logo" id="logo-home">${ICONS.store} ELECTRONIC STORE</a>
    <button class="mobile-toggle" id="mobileToggle" aria-label="Menú">${ICONS.menu}</button>
    <nav class="nav-links" id="navLinks">
      <a href="index.html" class="${currentPage === 'index.html' ? 'nav-link-active' : ''}">${NAV_ICONS.home} Inicio</a>
      <a href="products.html" class="${currentPage === 'products.html' ? 'nav-link-active' : ''}">${NAV_ICONS.grid} Productos</a>
      <a href="cart.html" class="${currentPage === 'cart.html' ? 'nav-link-active' : ''}">${NAV_ICONS.cartSmall} Carrito <span class="cart-badge" id="cart-count">0</span></a>
      <a href="orders.html" class="${currentPage === 'orders.html' ? 'nav-link-active' : ''}">${NAV_ICONS.orders} Pedidos</a>
      ${isAdmin ? `<a href="admin.html" class="${currentPage.startsWith('admin') ? 'nav-link-active' : ''}">${NAV_ICONS.admin} Admin</a>` : ''}
      ${isLoggedIn
        ? `<a href="#" id="logoutBtn" class="btn btn-ghost btn-sm">${NAV_ICONS.logout} Salir</a>`
        : `<a href="login.html" class="btn btn-primary btn-sm">${NAV_ICONS.login} Ingresar</a>`}
      <button class="btn-theme" id="darkToggle" aria-label="Cambiar tema">${ICONS.moon}</button>
    </nav>`;
  document.body.insertBefore(nav, document.body.firstChild);

  // Mobile menu
  document.getElementById('mobileToggle').addEventListener('click', () => {
    const links = document.getElementById('navLinks');
    const btn = document.getElementById('mobileToggle');
    const isOpen = links.classList.toggle('open');
    btn.innerHTML = isOpen ? ICONS.close : ICONS.menu;
  });

  // Logout
  const logoutBtn = document.getElementById('logoutBtn');
  if (logoutBtn) logoutBtn.addEventListener('click', (e) => { e.preventDefault(); logout(); });
}

