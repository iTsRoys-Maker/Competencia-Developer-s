function handleImgError(img) {
  const parent = img.parentElement;
  img.style.display = 'none';
  if (!parent.querySelector('.img-fallback')) {
    const fallback = document.createElement('div');
    fallback.className = 'img-fallback';
    fallback.innerHTML = ICONS.gadget;
    parent.appendChild(fallback);
  }
}

/* ===== STOCK BADGE ===== */
function stockBadge(stock) {
  if (stock > 10) return `<span class="badge badge-success">● En stock (${stock})</span>`;
  if (stock > 0) return `<span class="badge badge-warning">● Pocas unidades (${stock})</span>`;
  return `<span class="badge badge-danger">● Agotado</span>`;
}

/* ===== CART COUNT ===== */
async function updateCartCount() {
  const token = localStorage.getItem('token');
  const el = document.getElementById('cart-count');
  if (!token || !el) { if (el) el.textContent = '0'; return; }
  try {
    const res = await fetch(API_URL + '/cart', { headers: { 'Authorization': 'Bearer ' + token } });
    if (res.ok) {
      const cart = await res.json();
      el.textContent = cart.cantidadTotal || 0;
    }
  } catch (e) {}
}

